def в_роде(слово, род):
    """первый -> первая / первое, третий -> третья / третье."""
    if род == МУЖ:
        return слово
    if слово.endswith("ий"):                       # третий
        return слово[:-2] + ("ья" if род == ЖЕН else "ье")
    if слово.endswith(("ый", "ой")):               # первый, сороковой
        return слово[:-2] + ("ая" if род == ЖЕН else "ое")
    return слово


def _триада(n, женский=False):
    """Число 0..999 словами."""
    слова = []
    if n >= 100:
        слова.append(СОТНИ[n // 100])
        n %= 100
    if 10 <= n <= 19:
        слова.append(ДО_ДВАДЦАТИ[n - 10])
        return слова
    if n >= 20:
        слова.append(ДЕСЯТКИ[n // 10])
        n %= 10
    if n:
        слова.append((ЕДИНИЦЫ_Ж if женский else ЕДИНИЦЫ_М)[n])
    return слова


def форма(n, одна, две, пять):
    """Выбрать форму существительного при числе: год / года / лет."""
    сотня = abs(n) % 100
    if 11 <= сотня <= 14:
        return пять
    десяток = сотня % 10
    if десяток == 1:
        return одна
    if 2 <= десяток <= 4:
        return две
    return пять


def количественное(n, женский=False, год=False):
    """Количественное числительное: 1941 -> одна тысяча девятьсот сорок один."""
    if n == 0:
        return "ноль"
    слова = []
    for множитель, формы, ж in РАЗРЯДЫ:
        часть, n = divmod(n, множитель)
        if часть:
            куски = _триада(часть, ж)
            if год and множитель == 10 ** 3 and куски == ["одна"]:
                куски = []          # «тысяча девятьсот», а не «одна тысяча девятьсот»
            слова += куски + [форма(часть, *формы)]
    слова += _триада(n, женский)
    return " ".join(w for w in слова if w)


def порядковое(n, падеж=ИМ):
    """Порядковое числительное: 1941 -> тысяча девятьсот сорок первый."""
    if n in ПОРЯДКОВЫЕ:
        return ПОРЯДКОВЫЕ[n][падеж]
    for делитель in (10, 100, 1000):
        хвост = n % делитель
        if хвост and хвост in ПОРЯДКОВЫЕ:
            голова = n - хвост
            начало = количественное(голова, год=True) if голова else ""
            return (начало + " " + ПОРЯДКОВЫЕ[хвост][падеж]).strip()
    return количественное(n, год=True)      # не смогли — хотя бы без цифр


