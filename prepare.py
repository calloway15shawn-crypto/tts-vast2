def римское_в_число(s):
    значения = {"I": 1, "V": 5, "X": 10, "L": 50, "C": 100, "D": 500, "M": 1000}
    итог = 0
    for i, ch in enumerate(s):
        v = значения[ch]
        итог += -v if i + 1 < len(s) and v < значения[s[i + 1]] else v
    return итог


class Правки:
    """Собирает, что заменено автоматически и что осталось человеку."""

    def __init__(self):
        self.сделано = {}
        self.внимание = []

    def авто(self, вид):
        self.сделано[вид] = self.сделано.get(вид, 0) + 1

    def вручную(self, вид, строка, текст):
        self.внимание.append((вид, строка, текст))


def _номер_строки(текст, поз):
    return текст.count("\n", 0, поз) + 1


def заменить_числа(текст, правки):
    """Цифры -> слова. Года и века склоняются по следующему слову."""

    def год(m):
        n, хвост = int(m.group(1)), m.group(2)
        падеж = ПРЕДЛ if хвост.startswith("году") else (РОД if хвост.startswith("года") else ИМ)
        правки.авто("числа: года")
        правки.вручную("падеж числа", _номер_строки(текст, m.start()), m.group(0))
        return f"{порядковое(n, падеж)} {хвост}"

    def век(m):
        n, хвост = int(m.group(1)), m.group(2)
        падеж = ПРЕДЛ if хвост.startswith("веке") else (РОД if хвост.startswith("века") else ИМ)
        правки.авто("числа: века")
        return f"{порядковое(n, падеж)} {хвост}"

    def римское(m):
        n = римское_в_число(m.group(1))
        правки.авто("римские цифры")
        правки.вручную("римские цифры", _номер_строки(текст, m.start()), m.group(0))
        return порядковое(n, ИМ)

    def римское_с_хвостом(m):
        """«XX веке» -> «двадцатом веке»: падеж берём у следующего слова."""
        n, хвост = римское_в_число(m.group(1)), m.group(2)
        падеж = ПРЕДЛ if хвост.endswith(("е", "и")) else (РОД if хвост.endswith("а") else ИМ)
        правки.авто("римские цифры")
        правки.вручную("римские цифры", _номер_строки(текст, m.start()), m.group(0))
        return f"{порядковое(n, падеж)} {хвост}"

    def процент(m):
        n = int(m.group(1))
        правки.авто("проценты")
        правки.вручную("падеж числа", _номер_строки(текст, m.start()), m.group(0))
        return f"{количественное(n)} {форма(n, 'процент', 'процента', 'процентов')}"

    def порядковый_суффикс(m):
        n, окончание = int(m.group(1)), m.group(2)
        падеж = РОД if окончание in ("го", "ого") else (ПРЕДЛ if окончание == "м" else ИМ)
        род = СРЕД if окончание in ("е", "ое") else (ЖЕН if окончание in ("я", "ая") else МУЖ)
        правки.авто("порядковые с дефисом")
        return в_роде(порядковое(n, падеж), род)

    def дробь(m):
        целое, дробная = m.group(1), m.group(2)
        правки.вручную("дробное число", _номер_строки(текст, m.start()), m.group(0))
        if дробная == "5":
            правки.авто("дроби")
            return f"{количественное(int(целое))} с половиной"
        return m.group(0)      # не трогаем, пусть решит человек

    def при_букве(m):
        """Цифра, приклеенная к букве: «А4» -> «А четыре», «3D» -> «три D».

        Формат бумаги, модель, размер. Правила выше такие цифры не берут:
        между буквой и цифрой нет границы слова, поэтому там не срабатывает
        граница \b, а сервер озвучки цифры не принимает вовсе.
        """
        до, число, после = m.group(1), int(m.group(2)), m.group(3)
        правки.авто("цифры при букве")
        правки.вручную("цифры при букве", _номер_строки(текст, m.start()), m.group(0))
        return " ".join(x for x in (до, количественное(число), после) if x)

    def просто(m):
        n = int(m.group(0).replace(" ", "").replace(" ", ""))
        правки.авто("числа")
        правки.вручную("падеж числа", _номер_строки(текст, m.start()), m.group(0))
        return количественное(n)

    текст = re.sub(r"\b(\d{3,4})\s+(год\w*)", год, текст)
    текст = re.sub(r"\b(\d{1,2})\s+(век\w*|столети\w+)", век, текст)
    текст = re.sub(r"\b([MDCLXVI]+)\s+(век\w*|столети\w+|год\w*)", римское_с_хвостом, текст)
    текст = re.sub(r"\b(?=[MDCLXVI]{2,}\b)(M{0,4}(?:CM|CD|D?C{0,3})(?:XC|XL|L?X{0,3})(?:IX|IV|V?I{0,3}))\b",
                   римское, текст)
    текст = re.sub(r"\b(\d+)\s*%", процент, текст)
    текст = re.sub(r"\b(\d+)-(ый|ой|ая|ое|ые|го|ого|му|м|й|е|я|х)\b", порядковый_суффикс, текст)
    текст = re.sub(r"\b(\d+)[.,](\d+)\b", дробь, текст)
    текст = re.sub(r"([^\W\d_]*)(\d+)([^\W\d_]+)", при_букве, текст)
    текст = re.sub(r"([^\W\d_]+)(\d+)([^\W\d_]*)", при_букве, текст)
    текст = re.sub(r"\b\d[\d\s ]*\d\b|\b\d\b", просто, текст)
    return текст


def заменить_сокращения(текст, правки):
    for шаблон, замена in СОКРАЩЕНИЯ:
        текст, n = re.subn(шаблон, замена, текст)
        if n:
            правки.сделано["сокращения"] = правки.сделано.get("сокращения", 0) + n
    # «г.» — может быть и год, и город: решает человек
    for m in re.finditer(r"\bг\.", текст):
        правки.вручную("сокращение «г.»", _номер_строки(текст, m.start()),
                       текст[max(0, m.start() - 30):m.end() + 30].replace("\n", " "))
    return текст


def вернуть_ё(текст, правки):
    def замена(m):
        слово = m.group(0)
        нижнее = слово.lower()
        если = ЁФИКАЦИЯ.get(нижнее)
        if not если and нижнее.startswith("не") and len(нижнее) > 4:
            корень = ЁФИКАЦИЯ.get(нижнее[2:])
            если = "не" + корень if корень else None
        if not если:
            return слово
        правки.авто("восстановлена ё")
        return если.capitalize() if слово[0].isupper() else если

    return re.sub(r"\b[А-Яа-яЁё][А-Яа-яЁё-]*\b", замена, текст)


def убрать_ударения(текст, правки):
    """Знаки ударения Qwen3-TTS озвучивает как лишний звук: «за́мок» -> «заумок». Убираем."""
    чистый = "".join(ch for ch in текст if unicodedata.category(ch) != "Mn")
    if чистый != текст:
        правки.сделано["убраны знаки ударения"] = sum(
            1 for ch in текст if unicodedata.category(ch) == "Mn")
        правки.вручную("знаки ударения", 0,
                       "убраны: модель произносит их вслух. Омографы решайте перефразированием")
    return чистый


def привести_знаки(текст, правки):
    было = текст
    текст = текст.replace(" ", " ").replace("\t", " ")
    текст = re.sub(r"\.\.\.", "…", текст)
    текст = re.sub(r'"([^"\n]{1,120})"', r"«\1»", текст)
    текст = re.sub(r"(?<=\s)-(?=\s)", "—", текст)
    текст = re.sub(r"[#*_`~<>\[\]{}|\\]", "", текст)
    текст = re.sub(r"[ ]{2,}", " ", текст)
    текст = re.sub(r"[ ]+\n", "\n", текст)
    текст = re.sub(r"\n{3,}", "\n\n", текст)
    if текст != было:
        правки.авто("кавычки, тире, пробелы")
    return текст


def найти_ручное(текст, правки):
    for номер, строка in enumerate(текст.split("\n"), 1):
        for слово in set(re.findall(r"\b[а-яё-]+\b", строка.lower())):
            if слово in ОМОГРАФЫ:
                правки.вручную("омограф", номер, f"«{слово}» — уточните или перефразируйте")
        for m in re.finditer(r"\b[A-Za-zА-Яа-яЁё]+-?\d+[A-Za-zА-Яа-яЁё\d-]*\b", строка):
            правки.вручную("буквенно-цифровой код", номер,
                           f"«{m.group(0)}» — напишите словами, например «Эф сто четыре»")
        лат = ЛАТИНИЦА.findall(строка)
        if лат:
            правки.вручную("латиница", номер, ", ".join(sorted(set(лат))[:5]))
        for предложение in re.split(r"(?<=[.!?…])\s+", строка):
            if len(предложение) > ДЛИННОЕ_ПРЕДЛОЖЕНИЕ:
                правки.вручную("длинное предложение", номер,
                               f"{len(предложение)} симв. — будет разрезано короткой паузой")


