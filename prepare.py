def показать(путь, исходный, готовый, правки):
    print(f"\nФАЙЛ: {путь.name}")

    print("\nИСПРАВЛЕНО АВТОМАТИЧЕСКИ")
    if правки.сделано:
        for вид, n in sorted(правки.сделано.items(), key=lambda kv: -kv[1]):
            print(f"  {n:>4}  {вид}")
    else:
        print("      нечего исправлять")

    ошибки, _ = textproc.preflight(готовый, "ru")
    print("\nОСТАЛОСЬ ЦИФР (блокируют запуск):", len(ошибки))
    for e in ошибки[:5]:
        print(f"      ✖ {e}")

    группы = {}
    for вид, строка, текст in правки.внимание:
        группы.setdefault(вид, []).append((строка, текст))
    print(f"\nПРОВЕРИТЬ ГЛАЗАМИ: {len(правки.внимание)} мест")
    for вид, места in sorted(группы.items(), key=lambda kv: -len(kv[1])):
        print(f"  {вид} ({len(места)}):")
        for строка, текст in места[:6]:
            print(f"      строка {строка}: {текст[:88]}")
        if len(места) > 6:
            print(f"      … и ещё {len(места) - 6}")

    чистый = textproc.clean_text(готовый)
    куски = textproc.split_chunks(готовый)
    резкие = sum(1 for c in куски if c["pause"] == textproc.PAUSE_SPLIT)
    print("\nРАЗБОР НА ФРАГМЕНТЫ")
    print(f"      абзацев: {len(чистый.split(chr(10) + chr(10)))} (пауза 0,8 с после каждого)")
    print(f"      фрагментов: {len(куски)}, самый длинный {max(len(c['text']) for c in куски)} симв.")
    print(f"      принудительных разрезов: {резкие}" +
          ("  <- длинные предложения, пауза всего 0,12 с" if резкие else ""))
    print(f"\nОБЪЁМ: {len(чистый)} символов, примерно {len(чистый) / 14.0 / 60:.1f} мин аудио")


def main():
    for поток in (sys.stdout, sys.stderr):
        try:
            поток.reconfigure(encoding="utf-8")
        except (AttributeError, ValueError):
            pass
    p = argparse.ArgumentParser(description="Подготовка текста к озвучке")
    p.add_argument("файл")
    p.add_argument("-w", "--write", action="store_true", help="заменить исходный файл")
    args = p.parse_args()

    путь = Path(args.файл)
    if not путь.is_absolute():
        путь = ROOT / путь
    if not путь.exists():
        print(f"ОШИБКА: нет файла {путь}")
        sys.exit(1)

    сырой = путь.read_bytes()
    for кодировка in ("utf-8-sig", "cp1251"):
        try:
            исходный = сырой.decode(кодировка)
            break
        except UnicodeDecodeError:
            continue
    else:
        print("ОШИБКА: не удалось прочитать кодировку, сохраните файл в UTF-8")
        sys.exit(1)

    # Единый перевод строки: иначе при записи Windows добавит второй возврат каретки
    исходный = исходный.replace("\r\n", "\n").replace("\r", "\n")

    правки = Правки()
    готовый = убрать_ударения(исходный, правки)
    готовый = привести_знаки(готовый, правки)
    готовый = заменить_сокращения(готовый, правки)
    готовый = заменить_числа(готовый, правки)
    готовый = вернуть_ё(готовый, правки)
    найти_ручное(готовый, правки)

    показать(путь, исходный, готовый, правки)

    if args.write:
        путь.with_name(путь.stem + "_было.txt").write_text(исходный, encoding="utf-8")
        путь.write_text(готовый, encoding="utf-8")
        print(f"\nЗаписано в {путь.name}, копия исходного — {путь.stem}_было.txt")
    else:
        новый = путь.with_name(путь.stem + "_готов.txt")
        новый.write_text(готовый, encoding="utf-8")
        print(f"\nЗаписано: {новый.name}  (исходный не тронут)")
    print("Проверьте места из раздела «ПРОВЕРИТЬ ГЛАЗАМИ» — падежи машина не знает.\n")


if __name__ == "__main__":
    main()
